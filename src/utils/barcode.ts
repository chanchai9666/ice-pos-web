/**
 * แปลงสตริงที่ถูกพิมพ์ด้วยแป้นพิมพ์ภาษาไทยกลับเป็นภาษาอังกฤษ/ตัวเลขมาตรฐาน
 * ตัวอย่าง: "คคถจจตตจจ1234" -> "8850099001234"
 */
export function mapThaiToEnglishBarcode(input: string): string {
  if (!input) return '';
  return input
    .split('')
    .map((char) => THAI_TO_ENG_MAP[char] || char)
    .join('');
}

/**
 * ทำความสะอาดรหัสบาร์โค้ด ตัดช่องว่าง หัว/ท้าย และอักขระควบคุม
 */
export function cleanBarcode(rawInput: string): string {
  if (!rawInput) return '';
  const decoded = mapThaiToEnglishBarcode(rawInput);
  // ลบอักขระที่พิมพ์ไม่ได้
  return decoded.replace(/[\x00-\x1F\x7F]/g, '').trim();
}

/**
 * ตรวจสอบความถูกต้องเบื้องต้นว่าเป็นรหัสบาร์โค้ดหรือ SKU ที่สมเหตุสมผล
 */
export function isValidBarcodeString(code: string): boolean {
  if (!code) return false;
  const cleaned = cleanBarcode(code);
  // บาร์โค้ดทั่วไปมักมีความยาวอย่างน้อย 3 ตัวอักษรขึ้นไป
  return cleaned.length >= 3 && cleaned.length <= 64;
}
